// v0.005
// Minimal service worker for MVP — no caching implemented yet
self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(keys.map(key => caches.delete(key)))
    )
  );
  self.clients.claim();
});
